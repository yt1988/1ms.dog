#!/usr/bin/env node
// Writes the command-line tool's copy of the page's words (github.com/yt1988/https-latency-test-cli, webtexts.go):
// speed grades, groups, regions, everyday uses and the verdict, in every language, so the terminal says what the page
// says. Run it when one of these strings changes:  node scripts/cli-texts.mjs ../https-latency-test-cli/webtexts.go
import { readdir, writeFile } from "node:fs/promises";

const out = process.argv[2];
if (!out) { console.error("usage: node scripts/cli-texts.mjs <path to webtexts.go>"); process.exit(2); }
const KEYS = /^(vh_(allgood|far|near_slow|odd|down)|v_(allgood|far|near_slow|odd|down)|use_\w+|st_(great|ok|slow|blocked)|tier_\w+|cat_\w+|pk_\w+|seg_local|seg_global|med)$/;
const dir = new URL("../src/i18n/", import.meta.url);
const langs = (await readdir(dir)).filter(f => f.endsWith(".mjs")).map(f => f.slice(0, -4)).sort((a, b) => (b === "en") - (a === "en") || a.localeCompare(b));
let go = `// Code generated by scripts/cli-texts.mjs in github.com/yt1988/1ms.dog; DO NOT EDIT.\n// The page's own words for grades, groups, regions, uses and the verdict, so the terminal says what 1ms.dog says.\n\npackage main\n\nvar webTexts = map[string]map[string]string{\n`;
for (const l of langs) {
  const d = (await import(new URL(l + ".mjs", dir).href)).default;
  go += `\t${JSON.stringify(l)}: {\n`;
  for (const k of Object.keys(d).filter(k => KEYS.test(k)).sort()) go += `\t\t${JSON.stringify(k)}: ${JSON.stringify(d[k].replace(/‑/g, "-"))},\n`;
  go += `\t},\n`;
}
await writeFile(out, go + "}\n");
console.log("wrote " + out);
